"""Write .env with a random cookie secret and an easy-to-type GM passcode. Run: make env

Players don't need passcodes: they pick their character on the login screen.
"""

import secrets
import sys
from pathlib import Path

WORDS = """orbit tether cable horizon quasar ember signal static vector pulsar nebula comet photon
lumen relay cipher halo spindle reel vault seal mural lantern neon chrome dock queue oven ledger
velvet vent prism glass ring disc drift lull hush""".split()

env = Path(__file__).resolve().parents[1] / ".env"
if env.exists() and "--force" not in sys.argv:
    sys.exit(f"{env} already exists. Delete it or pass --force to replace it.")

gm = f"{secrets.choice(WORDS)}-{secrets.randbelow(9000) + 1000}"
env.write_text(
    "# Generated by scripts/make_env.py. Never commit this file.\n"
    f"LSO_SECRET={secrets.token_urlsafe(32)}\n"
    f"LSO_GM_PASSCODE={gm}\n"
    "LSO_AUTH_EPOCH=1\n"
    "LSO_SECURE_COOKIES=0\n"
)
print(f"Wrote {env}. The GM passcode is in it: run `make passcode` to see it.")
